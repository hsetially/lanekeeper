// Writes src/api/roles.generated.ts from the `x-required-role` of every operation of api/openapi.yaml (S4). The UI uses
// it to disable controls with a tooltip that names the role (the server enforces permissions regardless), and a test
// walks every write to prove it has a role. Run by `pnpm gen:api`; `--check` fails when the file is stale.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const SPEC = fileURLToPath(new URL("../../../api/openapi.yaml", import.meta.url));
const OUT = fileURLToPath(new URL("../../src/api/roles.generated.ts", import.meta.url));
const METHODS = ["get", "post", "put", "patch", "delete"];

export function renderRoles(yamlText) {
  const doc = parse(yamlText);
  const rows = [];
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const role = op["x-required-role"];
      if (typeof role !== "string") throw new Error(`${method.toUpperCase()} ${path} has no x-required-role`);
      rows.push({ id: op.operationId, method: method.toUpperCase(), path, role });
    }
  }
  rows.sort((a, b) => (a.id < b.id ? -1 : 1));
  const lines = rows.map((r) => `  ${r.id}: { method: "${r.method}", path: "${r.path}", role: "${r.role}" },`);
  return `// Generated by web/scripts/api/gen-roles.mjs from api/openapi.yaml. Do not edit; run \`pnpm gen:api\`.

export type OperationRole = "none" | "viewer" | "editor" | "operator" | "admin";

export const OPERATION_ROLES = {
${lines.join("\n")}
} as const satisfies Record<string, { method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE"; path: string; role: OperationRole }>;

export type OperationId = keyof typeof OPERATION_ROLES;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderRoles(readFileSync(SPEC, "utf8"));
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
      console.error("src/api/roles.generated.ts is stale; run `pnpm gen:api`");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
  }
}
