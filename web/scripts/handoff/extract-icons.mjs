// The icon set: one lucide-react named export per design/handoff/screens/assets/icons/*.svg.
// The SVG files themselves are never shipped (the handoff recommends inline components, and the
// CSS-mask form would be about 80 requests); only their names matter.
import { readdirSync } from "node:fs";
import { join } from "node:path";
import { HANDOFF_DIR } from "./dc-parse.mjs";

const BY = "web/scripts/handoff/extract-icons.mjs";

export const pascalCase = (kebab) =>
  kebab
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

export function buildIcons() {
  return readdirSync(join(HANDOFF_DIR, "assets", "icons"))
    .filter((f) => f.endsWith(".svg"))
    .map((f) => f.replace(/\.svg$/, ""))
    .sort();
}

export function renderIconsTs(files) {
  const names = files.map(pascalCase);
  return `// Generated by ${BY} from design/handoff/screens/assets/icons/*.svg. Do not edit; run \`pnpm gen:handoff\`.
// Named re-exports only, so a route chunk bundles just the icons it imports.
export {
${names.map((n) => `  ${n},`).join("\n")}
} from "lucide-react";
`;
}
