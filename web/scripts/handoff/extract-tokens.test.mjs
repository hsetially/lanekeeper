import { describe, expect, it } from "vitest";
import {
  buildTokens,
  parseCssBlocks,
  renderThemeCss,
  renderTokensCss,
  renderTokensTs,
  tailwindColourKey,
} from "./extract-tokens.mjs";

describe("parseCssBlocks", () => {
  it("reads custom properties per selector, in source order, and ignores comments", () => {
    const css = `
      /* header */
      :root {
        --a: #fff; --b: 4px; /* inline */
        --grad: repeating-linear-gradient(135deg, #f5f6f8 0 4px, #eef0f3 4px 8px);
        color-scheme: light;
      }
      .dark, [data-theme="dark"] { --a: #000; color-scheme: dark; }`;
    const blocks = parseCssBlocks(css);
    expect(blocks.map((b) => b.selector)).toEqual([":root", '.dark, [data-theme="dark"]']);
    expect(blocks[0].vars).toEqual([
      ["--a", "#fff"],
      ["--b", "4px"],
      ["--grad", "repeating-linear-gradient(135deg, #f5f6f8 0 4px, #eef0f3 4px 8px)"],
    ]);
    expect(blocks[0].other).toEqual([["color-scheme", "light"]]);
    expect(blocks[1].vars).toEqual([["--a", "#000"]]);
  });

  it("rejects CSS it does not understand instead of dropping it", () => {
    expect(() => parseCssBlocks("@media (min-width: 1px) { :root { --a: 1; } }")).toThrow(/unsupported/i);
    expect(() => parseCssBlocks(":root { --a: 1 }\n:root { --a: 2; }")).toThrow(/duplicate/i);
  });
});

describe("tailwindColourKey", () => {
  it("keeps the handoff name minus its prefix, as the Engineering Handoff page says", () => {
    expect(tailwindColourKey("--status-sync-fg")).toBe("--color-status-sync-fg");
    expect(tailwindColourKey("--primary-hover")).toBe("--color-primary-hover");
  });
});

describe("buildTokens on the real handoff", () => {
  const tokens = buildTokens();

  it("has the semantic colours in both themes and the ramps in :root only", () => {
    expect(tokens.light["--background"]).toBe("#ffffff");
    expect(tokens.dark["--background"]).toBe("#0e1116");
    expect(tokens.ramps["--gray-950"]).toBe("#0e1116");
    expect(tokens.light["--gray-950"]).toBeUndefined();
    expect(tokens.dark["--gray-950"]).toBeUndefined();
    expect(Object.keys(tokens.ramps).length).toBe(22);
  });

  it("gives every semantic token a dark value", () => {
    const missing = Object.keys(tokens.light).filter((k) => !(k in tokens.dark));
    expect(missing).toEqual([]);
  });

  it("keeps non-colour tokens separate and shared by both themes", () => {
    expect(tokens.shared["--text-sm"]).toBe("13px");
    expect(tokens.shared["--row-diff"]).toBe("18px");
    expect(tokens.shared["--radius-sm"]).toBe("4px");
    expect(tokens.light["--text-sm"]).toBeUndefined();
  });
});

describe("renderers", () => {
  const tokens = buildTokens();

  it("writes :root and a dark block that answers to .dark and [data-theme=dark]", () => {
    const css = renderTokensCss(tokens);
    expect(css).toMatch(/^\/\* Generated by/);
    expect(css).toContain(":root {");
    expect(css).toContain('.dark,\n[data-theme="dark"] {');
    expect(css).toContain("color-scheme: light;");
    expect(css).toContain("color-scheme: dark;");
    expect(css).not.toContain("--gray-950: #0e1116;\n  --gray-950"); // no duplicates
  });

  it("maps every semantic colour and nothing from the ramps into the Tailwind theme", () => {
    const css = renderThemeCss(tokens);
    expect(css).toContain("@theme inline {");
    expect(css).toContain("--color-status-untracked-border: var(--status-untracked-border);");
    expect(css).toContain("--color-overlay: var(--overlay);");
    expect(css).toContain("--background-image-diff-empty: var(--diff-empty-bg);");
    expect(css).toContain("--text-sm: 13px;");
    expect(css).toContain("--text-sm--line-height: 18px;");
    expect(css).not.toMatch(/--color-gray-/);
    expect(css).not.toMatch(/--color-blue-/);
  });

  it("writes a typed module with the generated header", () => {
    const ts = renderTokensTs(tokens);
    expect(ts).toMatch(/^\/\/ Generated by/);
    expect(ts).toContain("export const TOKENS = ");
    expect(ts).toContain("as const;");
  });
});
