import { describe, expect, it } from "vitest";
import { buildPairs, renderPairsTs } from "./extract-pairs.mjs";

describe("extract-pairs (Style Guide PAIRS, TOKENS, STATUS)", () => {
  const data = buildPairs();

  it("reads the 45 contrast pairs: 35 at 4.5:1 and 10 at 3:1", () => {
    expect(data.pairs).toHaveLength(45);
    expect(data.pairs.filter((p) => p.min === 4.5)).toHaveLength(35);
    expect(data.pairs.filter((p) => p.min === 3)).toHaveLength(10);
    expect(data.pairs[0]).toEqual({ fg: "--foreground", bg: "--background", min: 4.5 });
    expect(data.pairs.at(-1)).toEqual({ fg: "--agent-offline", bg: "--background", min: 3 });
  });

  it("expands the per-status pairs from the STATUS list", () => {
    expect(data.pairs).toContainEqual({ fg: "--status-untracked-fg", bg: "--status-untracked-bg", min: 4.5 });
    expect(data.pairs).toContainEqual({ fg: "--status-approval-fg", bg: "--status-approval-bg", min: 4.5 });
  });

  it("lists the 82 token names the Style Guide requires", () => {
    expect(data.styleGuideTokens).toHaveLength(82);
    expect(new Set(data.styleGuideTokens).size).toBe(82);
    expect(data.styleGuideTokens).toContain("--status-conflict-border");
  });

  it("keeps the ten status vocabularies with label, icon and border style", () => {
    expect(data.status.map((s) => s.key)).toEqual([
      "sync", "git", "nfs", "conflict", "intentional", "unknown", "untracked", "restart", "locked", "approval",
    ]);
    expect(data.status.find((s) => s.key === "untracked")).toMatchObject({ label: "Untracked", icon: "circle-dashed", border: "dashed" });
    expect(data.status.find((s) => s.key === "sync")).toMatchObject({ label: "In sync", icon: "check", border: "solid", kind: "Drift" });
  });

  it("renders a typed module", () => {
    const ts = renderPairsTs(data);
    expect(ts).toMatch(/^\/\/ Generated by/);
    expect(ts).toContain("export const PAIRS = ");
    expect(ts).toContain("export const STYLE_GUIDE_TOKENS = ");
    expect(ts).toContain("export const STATUS = ");
  });
});
