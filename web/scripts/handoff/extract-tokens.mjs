// Design tokens: design/handoff/screens/tokens/{colors,typography,spacing}.css -> web/src/styles/tokens.css,
// the Tailwind theme mapping and a typed copy for tests. Pure functions plus a small writer (see generate.mjs).
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { HANDOFF_DIR } from "./dc-parse.mjs";
import { tsModule } from "./render.mjs";

export const GENERATED_BY = "web/scripts/handoff/extract-tokens.mjs";
const SOURCES = "design/handoff/screens/tokens/{colors,typography,spacing}.css";

// ---------------------------------------------------------------------------------------------
// A deliberately small CSS reader: flat rule blocks of declarations, nothing else.

function splitDeclarations(body) {
  const out = [];
  let depth = 0;
  let current = "";
  for (const ch of body) {
    if (ch === "(") depth += 1;
    if (ch === ")") depth -= 1;
    if (ch === ";" && depth === 0) {
      out.push(current);
      current = "";
    } else current += ch;
  }
  if (current.trim()) out.push(current);
  return out.map((d) => d.trim()).filter(Boolean);
}

export function parseCssBlocks(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const blocks = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let consumed = 0;
  for (const match of text.matchAll(re)) {
    const gap = text.slice(consumed, match.index).trim();
    if (gap) throw new Error(`unsupported CSS outside a rule: ${gap.slice(0, 40)}`);
    consumed = match.index + match[0].length;
    const selector = match[1].trim().replace(/\s+/g, " ");
    if (selector.startsWith("@")) throw new Error(`unsupported at-rule ${selector}`);
    if (blocks.some((b) => b.selector === selector)) throw new Error(`duplicate selector ${selector}`);
    const vars = [];
    const other = [];
    const seen = new Set();
    for (const decl of splitDeclarations(match[2])) {
      const colon = decl.indexOf(":");
      if (colon < 0) throw new Error(`unsupported declaration: ${decl}`);
      const name = decl.slice(0, colon).trim();
      const value = decl.slice(colon + 1).trim().replace(/\s+/g, " ");
      if (seen.has(name)) throw new Error(`duplicate declaration ${name} in ${selector}`);
      seen.add(name);
      (name.startsWith("--") ? vars : other).push([name, value]);
    }
    blocks.push({ selector, vars, other });
  }
  const rest = text.slice(consumed).trim();
  if (rest) throw new Error(`unsupported CSS after the last rule: ${rest.slice(0, 40)}`);
  return blocks;
}

// ---------------------------------------------------------------------------------------------

const DARK_SELECTOR = '.dark, [data-theme="dark"]';
const RAMP_RE = /^--(gray|blue)-\d+$/;
// Themed tokens that are not colours in the Tailwind sense.
const NOT_A_COLOUR = new Set(["--shadow-popover", "--diff-empty-bg"]);

function readCss(name) {
  return readFileSync(join(HANDOFF_DIR, "tokens", name), "utf8");
}

function toObject(pairs, into = {}) {
  for (const [k, v] of pairs) {
    if (k in into) throw new Error(`duplicate token ${k}`);
    into[k] = v;
  }
  return into;
}

export function buildTokens() {
  const colours = parseCssBlocks(readCss("colors.css"));
  const root = colours.find((b) => b.selector === ":root");
  const dark = colours.find((b) => b.selector === DARK_SELECTOR);
  if (!root || !dark || colours.length !== 2) throw new Error("colors.css must hold exactly :root and the dark block");

  const ramps = {};
  const light = {};
  for (const [k, v] of root.vars) (RAMP_RE.test(k) ? ramps : light)[k] = v;
  const darkVars = toObject(dark.vars);

  const shared = {};
  for (const file of ["typography.css", "spacing.css"]) {
    const blocks = parseCssBlocks(readCss(file));
    if (blocks.length !== 1 || blocks[0].selector !== ":root") throw new Error(`${file} must hold exactly :root`);
    toObject(blocks[0].vars, shared);
  }
  const scheme = (block) => Object.fromEntries(block.other)["color-scheme"];
  return {
    ramps,
    light,
    dark: darkVars,
    shared,
    colorScheme: { light: scheme(root), dark: scheme(dark) },
  };
}

// ---------------------------------------------------------------------------------------------
// Renderers

const header = (comment) => `${comment} Generated by ${GENERATED_BY} from ${SOURCES}. Do not edit; run \`pnpm gen:handoff\`.`;

function declarations(map, indent = "  ") {
  return Object.entries(map)
    .map(([k, v]) => `${indent}${k}: ${v};`)
    .join("\n");
}

export function renderTokensCss(t) {
  return `${header("/*")} */
:root {
  /* Neutral and brand ramps. Same in both themes; components use the semantic tokens, never these. */
${declarations(t.ramps)}

  /* Semantic colours, light */
${declarations(t.light)}

  /* Typography and spacing. Same in both themes. */
${declarations(t.shared)}

  color-scheme: ${t.colorScheme.light};
}

.dark,
[data-theme="dark"] {
${declarations(t.dark)}

  color-scheme: ${t.colorScheme.dark};
}
`;
}

export function tailwindColourKey(name) {
  return `--color-${name.slice(2)}`;
}

export function renderThemeCss(t) {
  const colourLines = Object.keys(t.light)
    .filter((k) => !NOT_A_COLOUR.has(k))
    .map((k) => `  ${tailwindColourKey(k)}: var(${k});`);

  const text = [];
  for (const [k, v] of Object.entries(t.shared)) {
    const m = /^--text-(.+)$/.exec(k);
    if (!m) continue;
    const lead = t.shared[`--leading-${m[1]}`];
    if (!lead) throw new Error(`${k} has no --leading-${m[1]}`);
    text.push(`  --text-${m[1]}: ${v};`, `  --text-${m[1]}--line-height: ${lead};`);
  }

  const weight = (k) => {
    const v = t.shared[k];
    if (!v) throw new Error(`missing ${k}`);
    return v;
  };

  return `${header("/*")} */
/* Only the handoff vocabulary exists as utilities: Tailwind's own palette, font sizes, radii,
   weights and shadows are cleared first. One shadow, 4px and 6px radii, weights 400 to 600. */
@theme {
  --color-*: initial;
  --font-*: initial;
  --font-weight-*: initial;
  --text-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --spacing: 4px;
}

/* Every colour resolves through var(--name), so switching the theme class needs no rebuild.
   The ramps (--gray-*, --blue-*) are deliberately absent: there is no bg-gray-500 utility. */
@theme inline {
${colourLines.join("\n")}

  --background-image-diff-empty: var(--diff-empty-bg);
  --shadow-popover: var(--shadow-popover);

  --font-sans: ${t.shared["--font-sans"]};
  --font-mono: ${t.shared["--font-mono"]};

${text.join("\n")}

  --font-weight-normal: ${weight("--weight-regular")};
  --font-weight-medium: ${weight("--weight-medium")};
  --font-weight-semibold: ${weight("--weight-semibold")};

  --tracking-tight: ${t.shared["--tracking-tight"]};
  --tracking-caps: ${t.shared["--tracking-caps"]};

  --radius: ${t.shared["--radius"]};
  --radius-sm: ${t.shared["--radius-sm"]};
  --radius-md: ${t.shared["--radius-md"]};

  --ease-out: ${t.shared["--ease-out"]};
}
`;
}

export function renderTokensTs(t) {
  return `${tsModule(GENERATED_BY, SOURCES, [["TOKENS", t]])}
export type TokenName = keyof typeof TOKENS.light;
`;
}
