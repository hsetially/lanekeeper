//! The hub-to-hub messages (`proto/replica.proto`, private to this crate) and their validation (S11, S22).
//!
//! What a replica receives from a peer is validated like what it receives from an agent: the swimlane is a [`SwimlaneId`],
//! the command goes through `proto::convert` (size, enum and path checks happen before a domain value exists), and the
//! timeout is bounded. [`ForwardCall::try_from`] is the one decoding path, and the fuzz target `hub_forward_request` drives it.

use std::time::Duration;

use domain::{AgentReply, HubCommand, SwimlaneId};
use ports::GatewayError;
use proto::convert::{FromAgent, ToAgent};
use proto::limits::MAX_MESSAGE_BYTES;

use super::local::Epoch;

/// The code generated by `build.rs` from `proto/replica.proto`.
///
/// Generated code does not follow the workspace's pedantic style, so the lints are relaxed here and only here.
#[allow(
    clippy::all,
    clippy::pedantic,
    clippy::nursery,
    missing_docs,
    missing_debug_implementations,
    unreachable_pub,
    unused_qualifications
)]
pub mod pb {
    tonic::include_proto!("lanekeeper.replica.v1");
}

/// The largest forward message: a command can carry 3 MiB of file bytes inside the contract's 4 MiB message, and the
/// envelope (swimlane, epoch, timeout) adds a few bytes.
pub const MAX_FORWARD_BYTES: usize = MAX_MESSAGE_BYTES + 4096;

/// The longest an owner waits for an agent on a peer's behalf.
pub const MAX_FORWARD_TIMEOUT: Duration = Duration::from_secs(300);

/// Why a forward request is refused before anything is sent to an agent.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum ForwardRejected {
    #[error("the swimlane id is not valid")]
    Swimlane,
    #[error("the epoch is not valid")]
    Epoch,
    #[error("the timeout is not valid")]
    Timeout,
    #[error("the request carries no command")]
    NoCommand,
    #[error("the command is not valid")]
    Command,
    #[error("the message is not a command")]
    NotACommand,
}

/// A validated forward request.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForwardCall {
    pub swimlane: SwimlaneId,
    pub epoch: Epoch,
    pub timeout: Duration,
    pub command: HubCommand,
}

impl TryFrom<pb::ForwardRequest> for ForwardCall {
    type Error = ForwardRejected;

    fn try_from(request: pb::ForwardRequest) -> Result<Self, Self::Error> {
        let swimlane = SwimlaneId::parse(&request.swimlane_id).map_err(|_| ForwardRejected::Swimlane)?;
        let epoch = Epoch::from_wire(request.epoch)
            .filter(|epoch| epoch.get() > 0)
            .ok_or(ForwardRejected::Epoch)?;
        if request.timeout_ms == 0 {
            return Err(ForwardRejected::Timeout);
        }
        let timeout = Duration::from_millis(u64::from(request.timeout_ms)).min(MAX_FORWARD_TIMEOUT);
        let message = request.command.ok_or(ForwardRejected::NoCommand)?;
        let command = match ToAgent::from_proto(message) {
            Ok(Some(ToAgent::Command(command))) => command,
            // Configuration, acknowledgements and certificate renewals are the stream's own business, not a peer's to send.
            Ok(Some(_) | None) => return Err(ForwardRejected::NotACommand),
            Err(_) => return Err(ForwardRejected::Command),
        };
        Ok(Self {
            swimlane,
            epoch,
            timeout,
            command,
        })
    }
}

impl ForwardCall {
    #[must_use]
    pub fn into_proto(self) -> pb::ForwardRequest {
        pb::ForwardRequest {
            swimlane_id: self.swimlane.as_str().to_owned(),
            epoch: self.epoch.to_wire(),
            timeout_ms: u32::try_from(self.timeout.as_millis()).unwrap_or(u32::MAX),
            command: Some(ToAgent::Command(self.command).into_proto()),
        }
    }
}

/// The wire form of a gateway failure.
#[must_use]
pub fn error_to_wire(error: GatewayError) -> pb::ForwardError {
    match error {
        GatewayError::NotConnected => pb::ForwardError::NotConnected,
        GatewayError::Timeout => pb::ForwardError::Timeout,
        GatewayError::Busy => pb::ForwardError::Busy,
        GatewayError::Closed => pb::ForwardError::Closed,
        GatewayError::Unavailable => pb::ForwardError::Unavailable,
    }
}

/// A gateway failure from the wire. A value this build does not know is [`GatewayError::Unavailable`].
#[must_use]
pub fn error_from_wire(code: i32) -> GatewayError {
    match pb::ForwardError::try_from(code) {
        Ok(pb::ForwardError::NotConnected) => GatewayError::NotConnected,
        Ok(pb::ForwardError::Timeout) => GatewayError::Timeout,
        Ok(pb::ForwardError::Busy) => GatewayError::Busy,
        Ok(pb::ForwardError::Closed) => GatewayError::Closed,
        Ok(pb::ForwardError::Unavailable | pb::ForwardError::Unspecified) | Err(_) => {
            GatewayError::Unavailable
        }
    }
}

/// An agent's reply as it travels back: the very message the agent sent.
#[must_use]
pub fn reply_to_wire(reply: AgentReply) -> pb::ForwardReply {
    pb::ForwardReply {
        result: Some(pb::forward_reply::Result::Reply(
            FromAgent::Reply(reply).into_proto(),
        )),
    }
}

/// What a forward reply says: the agent's reply or a gateway failure. A reply that does not validate, or is not a reply to a
/// command, is [`GatewayError::Unavailable`]: the peer is misbehaving, and the caller learns nothing it could trust.
pub fn reply_from_wire(reply: pb::ForwardReply) -> Result<AgentReply, GatewayError> {
    match reply.result {
        Some(pb::forward_reply::Result::Reply(message)) => match FromAgent::from_proto(message) {
            Ok(Some(FromAgent::Reply(reply))) => Ok(reply),
            _ => Err(GatewayError::Unavailable),
        },
        Some(pb::forward_reply::Result::Error(code)) => Err(error_from_wire(code)),
        None => Err(GatewayError::Unavailable),
    }
}
