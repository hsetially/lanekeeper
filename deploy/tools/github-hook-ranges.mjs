// GitHub's webhook delivery ranges, for the Cloud Armor rule on /hooks/github (09/T3; S18, P2, Q28).
//
//   node deploy/tools/github-hook-ranges.mjs --write    read the `hooks` list of https://api.github.com/meta and write
//                                                        deploy/values/hub/github-hook-ranges.yaml
//   node deploy/tools/github-hook-ranges.mjs --check    exit 1 unless that file equals GitHub's list now (the nightly job)
//   --meta FILE   read a saved /meta document instead of the network (the test uses a synthetic one)
//   --out FILE    write or check FILE instead of the default
//
// The list is GitHub's and is never typed in: a range that is not in GitHub's list would let someone else's server call the hub's
// webhook path, and a range that is missing would drop deliveries. What is read from the network is data, so it is checked before
// it is used: it must have a `hooks` list of at most 64 CIDRs, none of them wider than /16 (IPv4) or /32 (IPv6), because the
// ranges end up in a Cloud Armor expression and a garbled answer must not be able to open the path to the internet. Nothing is
// written unless the whole list passes. No dependencies; Node 22 or later (global fetch). Behind a proxy on Node 24 or later, set
// NODE_USE_ENV_PROXY=1.
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { isIPv6 } from 'node:net';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const META_URL = 'https://api.github.com/meta';
export const DEFAULT_OUT = join(here, '../values/hub/github-hook-ranges.yaml');
const MAX_RANGES = 64;
const MAX_BYTES = 1024 * 1024;
const TIMEOUT_MS = 20_000;

function validCidr(text) {
  const match = /^([0-9a-fA-F:.]+)\/(\d{1,3})$/.exec(text);
  if (!match) return null;
  const [, address, prefixText] = match;
  const prefix = Number(prefixText);
  if (address.includes(':')) {
    return isIPv6(address) && prefix <= 128 ? { v6: true, prefix } : null;
  }
  const octets = address.split('.');
  const ok = octets.length === 4 && octets.every((o) => /^\d{1,3}$/.test(o) && Number(o) <= 255);
  return ok && prefix <= 32 ? { v6: false, prefix } : null;
}

/** The hook ranges of a /meta document: validated, without duplicates, sorted. Throws with the reason. */
export function parseMeta(text) {
  let doc;
  try {
    doc = JSON.parse(text);
  } catch {
    throw new Error('the /meta document is not JSON');
  }
  if (!doc || !Array.isArray(doc.hooks)) throw new Error('the /meta document has no hooks list');
  if (doc.hooks.length === 0) throw new Error('the hooks list is empty');
  if (doc.hooks.length > MAX_RANGES) throw new Error(`the hooks list has more than ${MAX_RANGES} entries`);
  const ranges = new Set();
  for (const entry of doc.hooks) {
    if (typeof entry !== 'string') throw new Error(`a hooks entry is not a string: ${JSON.stringify(entry)}`);
    const cidr = validCidr(entry);
    if (!cidr) throw new Error(`${JSON.stringify(entry)} is not a CIDR`);
    if (cidr.prefix < (cidr.v6 ? 32 : 16)) throw new Error(`${entry} is too wide to be a webhook delivery range`);
    ranges.add(entry);
  }
  return [...ranges].sort();
}

export function render(ranges) {
  return [
    '# GENERATED by deploy/tools/github-hook-ranges.mjs from the `hooks` list of https://api.github.com/meta. Do not edit it:',
    '#   node deploy/tools/github-hook-ranges.mjs --write',
    `# The nightly job runs --check and fails when GitHub's list has moved. ${ranges.length} ranges.`,
    'cloudArmor:',
    '  githubHookRanges:',
    ...ranges.map((r) => `    - ${r}`),
    '',
  ].join('\n');
}

/** The ranges in a committed file: our own format only (a block list, or `[]` for the unresolved file). */
export function parseCommitted(text) {
  const lines = text.split('\n');
  const at = lines.findIndex((l) => /^\s*githubHookRanges:/.test(l));
  if (at < 0) throw new Error('the file has no githubHookRanges');
  if (/\[\s*\]\s*$/.test(lines[at])) return [];
  const ranges = [];
  for (const line of lines.slice(at + 1)) {
    const item = /^\s+-\s+(\S+)\s*$/.exec(line);
    if (!item) break;
    ranges.push(item[1]);
  }
  return ranges;
}

async function readLimited(response) {
  const reader = response.body.getReader();
  const chunks = [];
  let size = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    size += value.length;
    if (size > MAX_BYTES) {
      await reader.cancel();
      throw new Error(`the answer is larger than ${MAX_BYTES} bytes`);
    }
    chunks.push(value);
  }
  return Buffer.concat(chunks).toString('utf8');
}

async function networkText(url) {
  const response = await fetch(url, {
    headers: { Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28', 'User-Agent': 'lanekeeper-github-hook-ranges' },
    signal: AbortSignal.timeout(TIMEOUT_MS),
    redirect: 'error',
  });
  if (!response.ok) throw new Error(`HTTP ${response.status} from ${url}`);
  return readLimited(response);
}

/** /meta, with a bounded number of attempts and a jittered pause between them. */
export async function fetchMeta(fetchText, { attempts = 3, delayMs = 1000 } = {}) {
  let last;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      return await fetchText(META_URL);
    } catch (error) {
      last = error;
      if (attempt < attempts) await new Promise((r) => setTimeout(r, delayMs * attempt * (1 + Math.random())));
    }
  }
  throw last;
}

export async function run(argv, io = {}) {
  const log = io.log ?? console.log;
  const error = io.error ?? console.error;
  const fetchText = io.fetchText ?? networkText;
  let mode = null;
  let out = DEFAULT_OUT;
  let metaFile = null;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--write' || argv[i] === '--check') mode = argv[i].slice(2);
    else if (argv[i] === '--out' && argv[i + 1]) out = argv[(i += 1)];
    else if (argv[i] === '--meta' && argv[i + 1]) metaFile = argv[(i += 1)];
    else {
      error(`github-hook-ranges: unknown argument ${argv[i]}\nusage: github-hook-ranges.mjs --write|--check [--meta FILE] [--out FILE]`);
      return 2;
    }
  }
  if (!mode) {
    error('github-hook-ranges: say --write or --check');
    return 2;
  }
  let ranges;
  try {
    const text = metaFile ? readFileSync(metaFile, 'utf8') : await fetchMeta(fetchText);
    ranges = parseMeta(text);
  } catch (cause) {
    error(`github-hook-ranges: ${cause.message}; nothing was written`);
    return 1;
  }
  if (mode === 'write') {
    const temporary = `${out}.tmp`;
    writeFileSync(temporary, render(ranges));
    renameSync(temporary, out);
    log(`github-hook-ranges: ${ranges.length} ranges written to ${out}`);
    return 0;
  }
  if (!existsSync(out)) {
    error(`github-hook-ranges: ${out} does not exist; run --write`);
    return 1;
  }
  let committed;
  try {
    committed = parseCommitted(readFileSync(out, 'utf8'));
  } catch (cause) {
    error(`github-hook-ranges: ${out}: ${cause.message}`);
    return 1;
  }
  if (committed.length === 0) {
    error(`github-hook-ranges: ${out} is empty (unresolved): GitHub's webhooks would be denied. Run --write and commit it.`);
    return 1;
  }
  const missing = ranges.filter((r) => !committed.includes(r));
  const stale = committed.filter((r) => !ranges.includes(r));
  if (missing.length > 0 || stale.length > 0) {
    for (const r of missing) error(`github-hook-ranges: GitHub lists ${r}; the file lacks it`);
    for (const r of stale) error(`github-hook-ranges: the file has ${r}; GitHub no longer lists it`);
    error('github-hook-ranges: run --write and commit the result');
    return 1;
  }
  log(`github-hook-ranges: ${ranges.length} ranges equal GitHub's list`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exit(await run(process.argv.slice(2)));
}
